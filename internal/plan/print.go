package plan

import (
	"cmp"
	"fmt"
	"io"
	"slices"
	"strings"
)

// Write prints p as kanna gen --plan shows it: each task with what it runs,
// what it writes, and why it comes where it does.
func (p *Plan) Write(w io.Writer) {
	number := make(map[*Task]int, len(p.Tasks))
	for i, t := range p.Tasks {
		number[t] = i + 1
	}

	for i, t := range p.Tasks {
		if i > 0 {
			fmt.Fprintln(w)
		}
		fmt.Fprintf(w, "%d. %s:%d\n", number[t], p.Module.Rel(t.At[0].File), t.At[0].Line)
		line(w, "run:", strings.Join(t.Words(), " "))
		for _, d := range t.At[1:] {
			line(w, "also:", fmt.Sprintf("%s:%d", p.Module.Rel(d.File), d.Line))
		}
		for _, file := range t.Report.Writes {
			line(w, "writes:", p.Module.Rel(file))
		}
		for _, e := range shown(t) {
			line(w, "after:", fmt.Sprintf("%d — %s", number[e.From], e.Reason(p.Module)))
		}
		for _, e := range t.Ahead {
			line(w, "before:", fmt.Sprintf("%d, which is told what it needs is coming — %s", number[e.From], e.Reason(p.Module)))
		}
		for _, other := range t.Loose {
			if number[other] < number[t] {
				line(w, "order:", fmt.Sprintf("after %d by position alone; nothing tells which reads the other", number[other]))
			}
		}
	}

	if len(p.External) > 0 {
		if len(p.Tasks) > 0 {
			fmt.Fprintln(w)
		}
		fmt.Fprintln(w, "external prerequisites:")
		for _, e := range p.External {
			fmt.Fprintf(w, "  %s — generated by %s\n",
				strings.TrimPrefix(e.Package, p.Module.Path+"/"), strings.Join(e.Generators, ", "))
		}
	}
}

func line(w io.Writer, label, text string) {
	fmt.Fprintf(w, "   %-7s %s\n", label, text)
}

// shown returns the edges of t worth reading: one for each task it comes after,
// leaving out those that another of them comes after anyway.
func shown(t *Task) []Edge {
	best := make(map[*Task]Edge, len(t.After))
	for _, e := range t.After {
		if prev, ok := best[e.From]; !ok || e.Kind < prev.Kind {
			best[e.From] = e
		}
	}

	var edges []Edge
	for from, e := range best {
		implied := slices.ContainsFunc(t.After, func(other Edge) bool {
			return other.From != from && comesAfter(other.From, from)
		})
		if !implied {
			edges = append(edges, e)
		}
	}
	slices.SortFunc(edges, func(a, b Edge) int {
		return cmp.Or(
			strings.Compare(a.From.At[0].File, b.From.At[0].File),
			cmp.Compare(a.From.At[0].Line, b.From.At[0].Line),
		)
	})
	return edges
}

// comesAfter reports whether t comes after other, through any tasks between.
func comesAfter(t, other *Task) bool {
	for _, e := range t.After {
		if e.From == other || comesAfter(e.From, other) {
			return true
		}
	}
	return false
}
