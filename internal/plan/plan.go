// Package plan works out what kanna gen runs, in what order, and why.
//
// Every //go:generate go tool kanna-* line is a task. What a task reads and
// writes, its generator says; which packages import which, the module's
// hand-written files say. A task comes after the tasks that write into what it
// reads, which is no fixed order of the generators: what depends on what is in
// the packages of a module, not in the tools.
//
// None of it reads what generators wrote, so that the plan of a tree with their
// output is that of a tree without it.
package plan

import (
	"cmp"
	"context"
	"fmt"
	"go/token"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/go-kanna/internal/diag"

	"github.com/go-kanna/kanna/internal/generate"
	"github.com/go-kanna/kanna/internal/module"
)

// Plan is what a kanna gen runs.
type Plan struct {
	// Module is the module the plan is of.
	Module *module.Module

	// Tasks holds the tasks to run, in order.
	Tasks []*Task

	// External holds what the tasks read that kanna does not generate.
	External []External

	// Problems says what keeps the plan from starting.
	Problems []diag.Diag
}

// External is a package tasks read that is generated by something else.
type External struct {
	// Package is its import path.
	Package string

	// Generators names what wrote it.
	Generators []string
}

// Config says what to plan.
type Config struct {
	// Module is the module to plan a run of.
	Module *module.Module

	// Selection is what the command line selected.
	Selection module.Selection

	// Patterns holds the patterns as given, for saying what matches nothing.
	Patterns []string

	// GOROOT is what the directives run with.
	GOROOT string

	// Ask tells what a task reads and writes.
	Ask Asker
}

// Make plans a run. Whatever keeps it from starting is in Problems of a Plan
// that holds as much as could be told. The error says it could not plan at all.
func Make(ctx context.Context, cfg Config) (*Plan, error) {
	m := cfg.Module
	tasks, found := tasksOf(m, cfg.GOROOT)

	// One that cannot answer may be a producer of any other, so it stops the
	// plan wherever it is, unlike a line that is merely not selected.
	failed := askAll(ctx, cfg.Ask, tasks)
	tasks = slices.DeleteFunc(tasks, func(t *Task) bool {
		_, ok := failed[t]
		return ok
	})

	g, err := newGraph(m, tasks)
	if err != nil {
		return nil, err
	}

	chosen := g.selected(cfg.Selection)
	p := &Plan{Module: m}
	for _, l := range found {
		if cfg.Selection.Matches(dirOf(l.directive)) {
			p.Problems = append(p.Problems, l.diag)
		}
	}
	p.Problems = append(p.Problems, slices.SortedFunc(maps.Values(failed), byPosition)...)
	if len(cfg.Patterns) > 0 && len(chosen) == 0 && len(p.Problems) == 0 {
		p.Problems = append(p.Problems, diag.Errorf(token.Position{},
			"no //go:generate go tool kanna-* line matches %s", strings.Join(cfg.Patterns, " ")))
	}
	p.Problems = slices.Concat(p.Problems, conflicts(m, chosen), g.missing(chosen))
	p.External = g.external(chosen)

	ordered, cycle := order(chosen, g.edgesAmong(chosen))
	p.Tasks = ordered
	if cycle != nil {
		p.Problems = append(p.Problems, cycleDiag(m, cycle))
	}
	g.markLoose(chosen)
	return p, nil
}

func byPosition(a, b diag.Diag) int {
	return cmp.Or(strings.Compare(a.Pos.Filename, b.Pos.Filename), cmp.Compare(a.Pos.Line, b.Pos.Line))
}

// conflicts reports the files two tasks of tasks write.
func conflicts(m *module.Module, tasks []*Task) []diag.Diag {
	owners := make(map[string][]*Task)
	for _, t := range tasks {
		for _, w := range t.Report.Writes {
			owners[w] = append(owners[w], t)
		}
	}

	var ds []diag.Diag
	for _, file := range slices.Sorted(maps.Keys(owners)) {
		if ts := owners[file]; len(ts) > 1 {
			d := diag.Errorf(positionOf(ts[1].At[0]), "%s writes %s, which %s writes too",
				ts[1].Tool, m.Rel(file), locationOf(m, ts[0]))
			ds = append(ds, d.WithHints("a file has one owner: give each its own destination, or drop one of the lines"))
		}
	}
	return ds
}

// locationOf names t for a message.
func locationOf(m *module.Module, t *Task) string {
	return fmt.Sprintf("%s at %s:%d", t.Tool, m.Rel(t.At[0].File), t.At[0].Line)
}

// missingInputs reports what t reads that is not there.
func missingInputs(m *module.Module, t *Task) []diag.Diag {
	var ds []diag.Diag
	for _, path := range t.Report.Inputs {
		if _, err := os.Stat(path); err != nil {
			ds = append(ds, diag.Errorf(positionOf(t.At[0]), "%s reads %s, which is not there", t.Tool, m.Rel(path)))
		}
	}
	return ds
}

func dirOf(d generate.Directive) string {
	return filepath.Dir(d.File)
}
