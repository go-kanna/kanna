func TestFind_LeavesWhatDotDotDotLeaves(t *testing.T) {
	t.Parallel()

	dir := write(t, map[string]string{
		"a/a.go":            "package a\n",
		"testdata/t.go":     "package t\n",
		"vendor/v/v.go":     "package v\n",
		"_skip/s.go":        "package s\n",
		".hidden/h.go":      "package h\n",
		"nested/go.mod":     "module example.com/nested\n",
		"nested/n.go":       "package n\n",
		"a/notes.txt":       "not Go\n",
		"a/deep/testing.go": "package deep\n",
	})

	m := find(t, dir)

	got := slices.Sorted(maps.Keys(m.Packages))
	want := []string{"example.com/m/a", "example.com/m/a/deep"}
	if !slices.Equal(got, want) {
		t.Errorf("Packages = %q, want %q", got, want)
	}
}

func TestFind_Imports(t *testing.T) {
	t.Parallel()

	dir := write(t, map[string]string{
		"p/p.go":      "package p\n\nimport (\n\t\"fmt\"\n\n\t\"example.com/m/q\"\n)\n",
		"p/p2.go":     "package p\n\nimport \"example.com/m/q\"\n",
		"p/p_test.go": "package p\n\nimport \"example.com/m/test\"\n",
		"p/x_test.go": "package p_test\n\nimport \"example.com/m/x\"\n",
		"p/other.go":  "//go:build ignore\n\npackage main\n\nimport \"example.com/m/ignored\"\n",
		"p/p_gen.go": "// Code generated by kanna-di v0.0.6. DO NOT EDIT.\n\n" +
			"package p\n\nimport \"example.com/m/generated\"\n",
		"p/q_gen.go":    "// Code generated by kanna-di. DO NOT EDIT.\n\npackage p\n\nimport \"example.com/m/generated\"\n",
		"p/mock_gen.go": "// Code generated by mockgen. DO NOT EDIT.\n\npackage p\n\nimport \"example.com/m/mocked\"\n",
	})

	p := find(t, dir).Packages["example.com/m/p"]

	if want := []string{"example.com/m/mocked", "example.com/m/q", "fmt"}; !slices.Equal(p.Imports, want) {
		t.Errorf("Imports = %q, want %q", p.Imports, want)
	}
	if want := []string{"example.com/m/test", "example.com/m/x"}; !slices.Equal(p.TestImports, want) {
		t.Errorf("TestImports = %q, want %q", p.TestImports, want)
	}
	if p.Name != "p" {
		t.Errorf("Name = %q, want p", p.Name)
	}
	if len(p.Generated) != 2 {
		t.Errorf("Generated = %v, want the two of kanna", p.Generated)
	}
}

