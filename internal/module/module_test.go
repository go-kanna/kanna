func TestModule_Select(t *testing.T) {
	t.Parallel()

	dir := write(t, map[string]string{"a/b/b.go": "package b\n"})
	m := find(t, dir)
	a, b, c := filepath.Join(dir, "a"), filepath.Join(dir, "a", "b"), filepath.Join(dir, "c")

	tests := []struct {
		name     string
		cwd      string
		patterns []string
		want     []string
	}{
		{name: "the default", cwd: dir, want: []string{dir, a, b, c}},
		{name: "the default below the root", cwd: a, want: []string{a, b}},
		{name: "a directory", cwd: dir, patterns: []string{"./a"}, want: []string{a}},
		{name: "a tree", cwd: dir, patterns: []string{"./a/..."}, want: []string{a, b}},
		{name: "the working directory", cwd: a, patterns: []string{"."}, want: []string{a}},
		{name: "up", cwd: b, patterns: []string{"../../c"}, want: []string{c}},
		{name: "an import path", cwd: b, patterns: []string{"example.com/m/a/b"}, want: []string{b}},
		{name: "an import path tree", cwd: c, patterns: []string{"example.com/m/a/..."}, want: []string{a, b}},
		{name: "an absolute path", cwd: dir, patterns: []string{c}, want: []string{c}},
		{name: "two", cwd: dir, patterns: []string{"./a/b", "./c"}, want: []string{b, c}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			s, err := m.Select(tt.cwd, tt.patterns)
			if err != nil {
				t.Fatal(err)
			}
			for _, d := range []string{dir, a, b, c} {
				if got, want := s.Matches(d), slices.Contains(tt.want, d); got != want {
					t.Errorf("Matches(%s) = %v, want %v", d, got, want)
				}
			}
		})
	}
}

