// write writes files under a new directory, with a go.mod unless they hold one,
// and returns it, with the links of the temporary directory followed.
func write(t *testing.T, files map[string]string) string {
	t.Helper()

	dir, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := files["go.mod"]; !ok {
		files["go.mod"] = "module example.com/m\n\ngo 1.26.0\n"
	}
	for name, content := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func find(t *testing.T, dir string) *module.Module {
	t.Helper()

	m, err := module.Find(dir)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func TestFind_FromBelowTheRoot(t *testing.T) {
	t.Parallel()

	dir := write(t, map[string]string{"a/b/b.go": "package b\n"})

	m := find(t, filepath.Join(dir, "a", "b"))

	if m.Dir != dir || m.Path != "example.com/m" {
		t.Errorf("Find() = %s at %s, want example.com/m at %s", m.Path, m.Dir, dir)
	}
}

