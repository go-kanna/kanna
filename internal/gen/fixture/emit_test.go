package fixture_test

import (
	"bytes"
	"flag"
	"os"
	"testing"

	"github.com/go-kanna/kanna/internal/diag"
	"github.com/go-kanna/kanna/internal/gen/fixture"
	"github.com/go-kanna/kanna/internal/packages"
	"github.com/go-kanna/kanna/internal/scan"
)

var update = flag.Bool("update", false, "update golden files")

// TestEmitGolden runs the whole pipeline the CLI runs — load, scan, select,
// infer, emit — over a package on disk and pins the bytes it produces.
func TestEmitGolden(t *testing.T) {
	t.Parallel()

	res, err := packages.Load([]string{"./testdata/model"}, packages.Config{})
	if err != nil {
		t.Fatalf("packages.Load() error = %v", err)
	}
	if len(res.Packages) != 1 {
		t.Fatalf("packages = %d, want 1", len(res.Packages))
	}
	pkg := res.Packages[0]

	structs, ds := scan.Structs(res.Packages)
	if diag.HasErrors(ds) {
		t.Fatalf("scan: %s", diag.Format(ds))
	}

	targets, tds := fixture.Targets(structs)

	// The generic struct is the only thing worth a diagnostic here; the spaced
	// directive on Spaced adds the second.
	if len(tds) != 2 || diag.HasErrors(tds) {
		t.Fatalf("diagnostics = %s, want two warnings", diag.Format(tds))
	}

	plans, imports := fixture.Plans(targets, pkg.PkgPath, pkg.Name)

	got, err := fixture.Emit(fixture.EmitParams{
		PackageName: "fixture",
		SourceName:  pkg.Name,
		SourcePath:  pkg.PkgPath,
		Imports:     imports,
		Plans:       plans,
	})
	if err != nil {
		t.Fatalf("Emit() error = %v", err)
	}

	const golden = "testdata/fixture_gen.go.golden"

	if *update {
		if err := os.WriteFile(golden, got, 0o600); err != nil {
			t.Fatalf("update golden: %v", err)
		}
	}

	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}

	if !bytes.Equal(got, want) {
		t.Errorf("Emit() output differs from golden file.\ngot:\n%s\nwant:\n%s", got, want)
	}
}

func TestEmit(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name   string
		params fixture.EmitParams
		want   string
	}{
		{
			name: "no plans",
			params: fixture.EmitParams{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
			},
			want: "// Code generated by kanna. DO NOT EDIT.\n\npackage fixture\n",
		},
		{
			name: "plan without fields skips the gofakeit import",
			params: fixture.EmitParams{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Plans:       []fixture.Plan{{Name: "Empty"}},
			},
			want: `// Code generated by kanna. DO NOT EDIT.

package fixture

import (
	"example.com/app/model"
)

func Empty(setters ...func(m *model.Empty)) model.Empty {
	m := model.Empty{}
	for _, s := range setters {
		s(&m)
	}
	return m
}
`,
		},
		{
			name: "template fallback emits the mustGenerate helper",
			params: fixture.EmitParams{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Plans: []fixture.Plan{{
					Name: "User",
					Fields: []fixture.Assignment{
						{Name: "Code", Expr: `mustGenerate("###-####")`},
					},
				}},
			},
			want: `// Code generated by kanna. DO NOT EDIT.

package fixture

import (
	"github.com/brianvoe/gofakeit/v7"

	"example.com/app/model"
)

func User(setters ...func(m *model.User)) model.User {
	m := model.User{
		Code: mustGenerate("###-####"),
	}
	for _, s := range setters {
		s(&m)
	}
	return m
}

func mustGenerate(template string) string {
	s, err := gofakeit.Generate(template)
	if err != nil {
		panic(err)
	}
	return s
}
`,
		},
		{
			name: "plan with fields imports gofakeit",
			params: fixture.EmitParams{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Plans: []fixture.Plan{{
					Name: "User",
					Fields: []fixture.Assignment{
						{Name: "Name", Expr: "gofakeit.Name()"},
						{Name: "Profile", Expr: "Profile()"},
					},
				}},
			},
			want: `// Code generated by kanna. DO NOT EDIT.

package fixture

import (
	"github.com/brianvoe/gofakeit/v7"

	"example.com/app/model"
)

func User(setters ...func(m *model.User)) model.User {
	m := model.User{
		Name:    gofakeit.Name(),
		Profile: Profile(),
	}
	for _, s := range setters {
		s(&m)
	}
	return m
}
`,
		},
		{
			name: "an expression import joins the gofakeit group",
			params: fixture.EmitParams{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Imports:     []string{"github.com/google/uuid"},
				Plans: []fixture.Plan{{
					Name: "User",
					Fields: []fixture.Assignment{
						{Name: "ID", Expr: "uuid.MustParse(gofakeit.UUID())"},
					},
				}},
			},
			want: `// Code generated by kanna. DO NOT EDIT.

package fixture

import (
	"github.com/brianvoe/gofakeit/v7"
	"github.com/google/uuid"

	"example.com/app/model"
)

func User(setters ...func(m *model.User)) model.User {
	m := model.User{
		ID: uuid.MustParse(gofakeit.UUID()),
	}
	for _, s := range setters {
		s(&m)
	}
	return m
}
`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got, err := fixture.Emit(tt.params)
			if err != nil {
				t.Fatalf("Emit() error = %v", err)
			}

			if string(got) != tt.want {
				t.Errorf("Emit() = %q, want %q", got, tt.want)
			}
		})
	}
}
