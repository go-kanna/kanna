// runCLI drives the generator with buffers standing in for the process streams.
func runCLI(t *testing.T, dir string, args ...string) (int, string, string) {
	t.Helper()

	var stdout, stderr bytes.Buffer

	c := fixture.CLI{Out: &stdout, Err: &stderr, Version: "dev", Dir: dir}
	code := c.Run(args)

	return code, stdout.String(), stderr.String()
}

// readGenerated reads the generated fixture file under dest.
func readGenerated(t *testing.T, dest string) string {
	t.Helper()

	//nolint:gosec // the path is under t.TempDir
	out, err := os.ReadFile(filepath.Join(dest, "fixture_gen.go"))
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}

	return string(out)
}

func TestRun(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		args []string
		want int
	}{
		{
			name: "no args",
			args: nil,
			want: exit.Usage,
		},
		{
			name: "missing source",
			args: []string{"-destination", "./fixture"},
			want: exit.Usage,
		},
		{
			name: "missing destination",
			args: []string{"-source", "./model"},
			want: exit.Usage,
		},
		{
			name: "unknown flag",
			args: []string{"-source", "./model", "-destination", "./fixture", "-bogus"},
			want: exit.Usage,
		},
		{
			name: "unexpected argument",
			args: []string{"-source", "./model", "-destination", "./fixture", "extra"},
			want: exit.Usage,
		},
		{
			name: "help",
			args: []string{"-h"},
			want: exit.OK,
		},
		{
			// token.IsIdentifier rejects keywords; lock that in.
			name: "keyword package name",
			args: []string{"-source", "./testdata/model", "-destination", "./x", "-package", "func"},
			want: exit.Usage,
		},
		{
			name: "nonexistent source",
			args: []string{"-source", "./testdata/nonexistent", "-destination", "./fixture"},
			want: exit.Error,
		},
		{
			name: "source matching several packages",
			args: []string{"-source", "./testdata/...", "-destination", "./fixture"},
			want: exit.Error,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got, _, stderr := runCLI(t, "", tt.args...)
			if got != tt.want {
				t.Errorf("Run() = %d, want %d\nstderr: %s", got, tt.want, stderr)
			}
		})
	}
}

