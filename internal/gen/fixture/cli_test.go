func TestRunGenerateExcludeEverything(t *testing.T) {
	t.Parallel()

	dest := filepath.Join(t.TempDir(), "fixture")
	if err := os.MkdirAll(dest, 0o750); err != nil {
		t.Fatalf("mkdir: %v", err)
	}

	existing := filepath.Join(dest, "fixture_gen.go")
	if err := os.WriteFile(existing, []byte("package fixture // precious\n"), 0o600); err != nil {
		t.Fatalf("write existing file: %v", err)
	}

	args := []string{"-source", "./testdata/model", "-destination", dest, "-exclude", "User,Profile,Empty,Spaced"}

	code, _, stderr := runCLI(t, "", args...)
	if code != exit.Error {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.Error, stderr)
	}

	if !strings.Contains(stderr, "no fixture targets") {
		t.Errorf("stderr does not explain the empty result: %s", stderr)
	}

	if got := readGenerated(t, dest); got != "package fixture // precious\n" {
		t.Errorf("existing file was overwritten:\n%s", got)
	}
}

