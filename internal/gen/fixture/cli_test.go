func TestPackageName(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		override string
		dir      string
		// files, when non-nil, are written into the destination directory;
		// a nil map leaves the directory missing.
		files map[string]string
		want  string
	}{
		{
			name:     "override wins over the declared package",
			override: "fx",
			dir:      "fixture",
			files:    map[string]string{"fixture.go": "package fixture\n"},
			want:     "fx",
		},
		{
			name:  "declared package wins over the directory name",
			dir:   "fixtures",
			files: map[string]string{"employee_fixture.go": "package fixture\n"},
			want:  "fixture",
		},
		{
			name:  "a previously generated file does not pin the name",
			dir:   "fixture",
			files: map[string]string{"fixture_gen.go": "package stale\n"},
			want:  "fixture",
		},
		{
			name:  "external test files are ignored",
			dir:   "fixture",
			files: map[string]string{"fixture_test.go": "package fixture_test\n"},
			want:  "fixture",
		},
		{
			name: "a missing directory falls back to its name",
			dir:  "fixture",
			want: "fixture",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dest := filepath.Join(t.TempDir(), tt.dir)

			if tt.files != nil {
				if err := os.MkdirAll(dest, 0o750); err != nil {
					t.Fatalf("mkdir: %v", err)
				}

				for name, body := range tt.files {
					if err := os.WriteFile(filepath.Join(dest, name), []byte(body), 0o600); err != nil {
						t.Fatalf("write %s: %v", name, err)
					}
				}
			}

			if got := fixture.PackageName(tt.override, dest); got != tt.want {
				t.Errorf("packageName(%q, %q) = %q, want %q", tt.override, dest, got, tt.want)
			}
		})
	}
}

func TestFindGoMod(t *testing.T) {
	t.Parallel()

	// The test runs in internal/gen/fixture, so a relative path must still walk
	// up to the repository's go.mod.
	if got := fixture.FindGoMod("."); !strings.HasSuffix(got, "go.mod") {
		t.Errorf("findGoMod(%q) = %q, want a go.mod path", ".", got)
	}

	// The filesystem root is the only location guaranteed to sit outside every
	// module; a temp dir may live under a tree that has a go.mod.
	root := filepath.VolumeName(t.TempDir()) + string(filepath.Separator)
	if got := fixture.FindGoMod(root); got != "" {
		t.Errorf("findGoMod(%q) = %q, want empty", root, got)
	}
}

func TestParseFlags(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		args []string
		want fixture.Config
	}{
		{
			name: "required only",
			args: []string{"-source", "./model", "-destination", "./fixture"},
			want: fixture.Config{Source: "./model", Destination: "./fixture"},
		},
		{
			name: "all flags",
			args: []string{
				"-source", "./model", "-destination", "./fixture",
				"-package", "myfixture", "-exclude", "Foo,Bar",
			},
			want: fixture.Config{
				Source:      "./model",
				Destination: "./fixture",
				Package:     "myfixture",
				Excludes:    []string{"Foo", "Bar"},
			},
		},
		{
			name: "exclude with spaces and empties",
			args: []string{"-source", "./model", "-destination", "./fixture", "-exclude", " Foo, ,Bar,"},
			want: fixture.Config{Source: "./model", Destination: "./fixture", Excludes: []string{"Foo", "Bar"}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			var stderr bytes.Buffer

			got, err := fixture.ParseFlags(tt.args, &stderr)
			if err != nil {
				t.Fatalf("parseFlags() error = %v", err)
			}

			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("parseFlags() = %+v, want %+v", got, tt.want)
			}
		})
	}
}
