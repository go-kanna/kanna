func TestRunGenerate(t *testing.T) {
	t.Parallel()

	dest := filepath.Join(t.TempDir(), "fixture")

	code, stdout, stderr := runCLI(t, "", "-source", "./testdata/model", "-destination", dest)
	if code != exit.OK {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.OK, stderr)
	}

	got := readGenerated(t, dest)

	for _, want := range []string{
		"// Code generated by kanna. DO NOT EDIT.",
		"package fixture",
		"func User(setters ...func(m *model.User)) model.User {",
		"func Profile(setters ...func(m *model.Profile)) model.Profile {",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("generated file does not contain %q:\n%s", want, got)
		}
	}

	if !strings.Contains(stdout, filepath.Join(dest, "fixture_gen.go")) {
		t.Errorf("stdout does not report the written file: %q", stdout)
	}

	if !strings.Contains(stderr, "skipping generic struct Pair") {
		t.Errorf("stderr does not contain the generic warning: %s", stderr)
	}

	// The destination has no enclosing go.mod, so the tidy note stays quiet.
	if strings.Contains(stderr, "go mod tidy") {
		t.Errorf("stderr contains an unexpected go mod tidy note: %s", stderr)
	}
}

func TestRunGenerateTidyNote(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		gomod    string
		wantNote bool
	}{
		{
			name:     "gofakeit missing from the destination module",
			gomod:    "module example.com/consumer\n\ngo 1.25\n",
			wantNote: true,
		},
		{
			name:     "gofakeit already required",
			gomod:    "module example.com/consumer\n\ngo 1.25\n\nrequire github.com/brianvoe/gofakeit/v7 v7.15.0\n",
			wantNote: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(tt.gomod), 0o600); err != nil {
				t.Fatalf("write go.mod: %v", err)
			}

			dest := filepath.Join(dir, "fixture")

			code, _, stderr := runCLI(t, "", "-source", "./testdata/model", "-destination", dest)
			if code != exit.OK {
				t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.OK, stderr)
			}

			if got := strings.Contains(stderr, "go mod tidy"); got != tt.wantNote {
				t.Errorf("go mod tidy note printed = %t, want %t\nstderr: %s", got, tt.wantNote, stderr)
			}
		})
	}
}

func TestRunGenerateExclude(t *testing.T) {
	t.Parallel()

	dest := filepath.Join(t.TempDir(), "fixture")

	code, _, stderr := runCLI(t, "", "-source", "./testdata/model", "-destination", dest, "-exclude", "Profile")
	if code != exit.OK {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.OK, stderr)
	}

	got := readGenerated(t, dest)
	if strings.Contains(got, "func Profile(") {
		t.Errorf("generated file contains excluded fixture Profile:\n%s", got)
	}

	// User references Profile as a value field; with no fixture to call, the
	// field drops to its zero value rather than referring to a missing function.
	if strings.Contains(got, "Profile: Profile()") {
		t.Errorf("generated file calls the excluded fixture:\n%s", got)
	}
}

