package mapper_test

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/go-kanna/kanna/internal/exit"
	"github.com/go-kanna/kanna/internal/gen/mapper"
)

// These tests drive the CLI end to end against a throwaway module, which is the
// only way to see what the generator actually writes. The unit tests above cover
// flag parsing; everything they cannot reach — package loading, selector
// resolution, the file on disk — lives here.

// writeModule lays out a throwaway module under dir.
func writeModule(t *testing.T, dir string, files map[string]string) {
	t.Helper()

	for name, body := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatalf("mkdir: %v", err)
		}
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}
}

// runCLI drives the generator in dir with buffers standing in for the streams.
func runCLI(t *testing.T, dir string, args ...string) (int, string, string) {
	t.Helper()

	var stdout, stderr bytes.Buffer

	c := mapper.CLI{Out: &stdout, Err: &stderr, Version: "dev", Dir: dir}
	code := c.Run(args)

	return code, stdout.String(), stderr.String()
}

func readGenerated(t *testing.T, dir string) string {
	t.Helper()

	//nolint:gosec // the path is under t.TempDir
	out, err := os.ReadFile(filepath.Join(dir, "out", "mapper_gen.go"))
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}

	return string(out)
}

// baseModule is the smallest module the generator will run in: a root package
// for the "." pattern, and the two sides of one mapping.
func baseModule(model, wire string) map[string]string {
	return map[string]string{
		"go.mod":         "module example.com/app\n\ngo 1.25\n",
		"doc.go":         "package app\n",
		"model/model.go": model,
		"wire/wire.go":   wire,
	}
}

const pairFlag = "-types=example.com/app/model.User:example.com/app/wire.User"

func TestRunGenerate(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeModule(t, dir, baseModule(
		"package model\n\ntype User struct {\n\tID   int32\n\tName string\n}\n",
		"package wire\n\ntype User struct {\n\tID   int64\n\tName string\n}\n",
	))

	// Only the widening direction: int64 back into int32 would lose data, and
	// the generator is right to refuse it without a converter.
	code, stdout, stderr := runCLI(t, dir, pairFlag, "-direction=to", "-destination=./out", "-package=out")
	if code != exit.OK {
		t.Fatalf("Run() = %d, want %d\nstderr: %s\nstdout: %s", code, exit.OK, stderr, stdout)
	}

	got := readGenerated(t, dir)
	for _, want := range []string{
		"// Code generated by kanna. DO NOT EDIT.",
		"package out",
		"func UserToWire(src model.User) wire.User {",
		// int32 widens into int64 without a converter; the reverse would not.
		"ID:   int64(src.ID),",
		"Name: src.Name,",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("generated file does not contain %q:\n%s", want, got)
		}
	}
}

// A tag on a promoted field keeps applying. Copying the field anyway would leak
// data the author excluded, with nothing on stderr to say so.
func TestRunPromotedFieldKeepsItsTag(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeModule(t, dir, baseModule(
		"package model\n\ntype Base struct {\n\tSecret string `map:\"-\"`\n}\n\n"+
			"type User struct {\n\tBase\n\tName string\n}\n",
		"package wire\n\ntype User struct {\n\tSecret string\n\tName   string\n}\n",
	))

	code, _, stderr := runCLI(t, dir, pairFlag, "-direction=to", "-destination=./out", "-package=out")
	if code != exit.Error {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.Error, stderr)
	}
	if !strings.Contains(stderr, "wire.User.Secret") {
		t.Errorf("stderr does not report the excluded field: %s", stderr)
	}

	if _, err := os.Stat(filepath.Join(dir, "out", "mapper_gen.go")); !os.IsNotExist(err) {
		t.Error("a file was written despite the unmapped field")
	}
}

// A getter returning a value must not win over the field it wraps when the
// field's type already matches: a nil pointer would arrive as a pointer to a
// zero, which is the distinction the pointer was carrying.
func TestRunPreservesPointerNilness(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeModule(t, dir, baseModule(
		"package model\n\ntype User struct {\n\tNote *string\n}\n",
		"package wire\n\ntype User struct {\n\tNote *string\n}\n\n"+
			"func (x *User) GetNote() string {\n\tif x != nil && x.Note != nil {\n\t\treturn *x.Note\n\t}\n\treturn \"\"\n}\n",
	))

	code, _, stderr := runCLI(t, dir,
		"-types=example.com/app/wire.User:example.com/app/model.User",
		"-direction=to", "-destination=./out", "-package=out")
	if code != exit.OK {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.OK, stderr)
	}

	got := readGenerated(t, dir)
	if !strings.Contains(got, "Note: src.Note,") {
		t.Errorf("the pointer was not carried across directly:\n%s", got)
	}
	if strings.Contains(got, "GetNote()") {
		t.Errorf("the getter was preferred over the matching field:\n%s", got)
	}
}

// Every file in a directory agrees on its package clause, so -package cannot
// override what is already declared there.
func TestRunPackageConflict(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	files := baseModule(
		"package model\n\ntype User struct{ Name string }\n",
		"package wire\n\ntype User struct{ Name string }\n",
	)
	files["out/existing.go"] = "package out\n"
	writeModule(t, dir, files)

	code, _, stderr := runCLI(t, dir, pairFlag, "-destination=./out", "-package=different")
	if code != exit.Error {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.Error, stderr)
	}
	if !strings.Contains(stderr, "conflicts with package out") {
		t.Errorf("stderr does not explain the conflict: %s", stderr)
	}
}

// A file excluded by build constraints belongs to another platform. Its imports
// must not become packages to load, or generating would fail everywhere else.
func TestRunSkipsOtherPlatformFiles(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	files := baseModule(
		"package model\n\ntype User struct{ Name string }\n",
		"package wire\n\ntype User struct{ Name string }\n",
	)
	// A package that does not exist: reaching it at all fails the load.
	files["only_plan9.go"] = "//go:build plan9\n\npackage app\n\nimport _ \"example.com/app/nonexistent\"\n"
	writeModule(t, dir, files)

	code, _, stderr := runCLI(t, dir, pairFlag, "-destination=./out", "-package=out")
	if code != exit.OK {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.OK, stderr)
	}
}

// -check reports staleness without writing, and says so in a way that separates
// "not generated yet" from "changed".
func TestRunCheck(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeModule(t, dir, baseModule(
		"package model\n\ntype User struct{ Name string }\n",
		"package wire\n\ntype User struct{ Name string }\n",
	))

	code, _, stderr := runCLI(t, dir, pairFlag, "-destination=./out", "-package=out", "-check")
	if code != exit.Error {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.Error, stderr)
	}
	if !strings.Contains(stderr, "has not been generated yet") {
		t.Errorf("stderr does not distinguish a missing file: %s", stderr)
	}
	if _, err := os.Stat(filepath.Join(dir, "out", "mapper_gen.go")); !os.IsNotExist(err) {
		t.Error("-check wrote a file")
	}

	// Generate, then confirm -check is satisfied by the result.
	if code, _, stderr := runCLI(t, dir, pairFlag, "-destination=./out", "-package=out"); code != exit.OK {
		t.Fatalf("generate failed: %d\nstderr: %s", code, stderr)
	}
	if code, _, stderr := runCLI(t, dir, pairFlag, "-destination=./out", "-package=out", "-check"); code != exit.OK {
		t.Fatalf("-check on fresh output = %d, want %d\nstderr: %s", code, exit.OK, stderr)
	}
}

// A hand-written file is never overwritten, however the flags point at it.
func TestRunRefusesToOverwriteHandWritten(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	files := baseModule(
		"package model\n\ntype User struct{ Name string }\n",
		"package wire\n\ntype User struct{ Name string }\n",
	)
	files["out/mapper_gen.go"] = "package out\n\n// Written by hand.\n"
	writeModule(t, dir, files)

	code, _, stderr := runCLI(t, dir, pairFlag, "-destination=./out", "-package=out")
	if code != exit.Error {
		t.Fatalf("Run() = %d, want %d\nstderr: %s", code, exit.Error, stderr)
	}
	if !strings.Contains(stderr, "generated-code header") {
		t.Errorf("stderr does not explain the refusal: %s", stderr)
	}

	if got := readGenerated(t, dir); !strings.Contains(got, "Written by hand.") {
		t.Errorf("the hand-written file was overwritten:\n%s", got)
	}
}
