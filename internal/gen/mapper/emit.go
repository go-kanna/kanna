package mapper

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"strconv"

	"github.com/go-kanna/kanna/internal/imports"
)

// emitFile renders the generated Go source for plans. Output is
// gofmt-formatted; indentation is left to format.Source.
func emitFile(pkgName, outputPkgPath string, plans []*funcPlan) ([]byte, error) {
	e := &emitter{imports: newImportTracker(outputPkgPath)}
	var body bytes.Buffer
	for i, p := range plans {
		if i > 0 {
			body.WriteByte('\n')
		}
		e.emitFunc(&body, p)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by kanna. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", pkgName)
	writeImports(&out, e.imports)
	out.WriteByte('\n')
	out.Write(body.Bytes())

	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code (kanna bug): %w\n%s", err, out.Bytes())
	}
	return src, nil
}

type emitter struct {
	imports *imports.Tracker
	tmpN    int
}

// fnCtx carries per-function emission state.
type fnCtx struct {
	buf  *bytes.Buffer
	plan *funcPlan
	zero string // zero-value expression of the destination type
}

func (e *emitter) tmp(prefix string) string {
	n := e.tmpN
	e.tmpN++
	return prefix + strconv.Itoa(n)
}

func (e *emitter) typeExpr(t types.Type) string {
	return types.TypeString(t, e.imports.Qualifier)
}

func (e *emitter) zeroExpr(t types.Type) string {
	if isPointer(t) {
		return "nil"
	}
	return e.typeExpr(t) + "{}"
}

func isPointer(t types.Type) bool {
	_, ok := types.Unalias(t).(*types.Pointer)
	return ok
}

func (e *emitter) emitFunc(buf *bytes.Buffer, p *funcPlan) {
	e.tmpN = 0
	fn := &fnCtx{buf: buf, plan: p, zero: e.zeroExpr(p.dst)}

	srcT, dstT := e.typeExpr(p.src), e.typeExpr(p.dst)
	fmt.Fprintf(buf, "// %s maps %s to %s.\n", p.name, typeLabel(p.src), typeLabel(p.dst))
	if p.returnsError {
		fmt.Fprintf(buf, "func %s(src %s) (%s, error) {\n", p.name, srcT, dstT)
	} else {
		fmt.Fprintf(buf, "func %s(src %s) %s {\n", p.name, srcT, dstT)
	}
	if isPointer(p.src) {
		fmt.Fprintf(buf, "if src == nil {\nreturn %s\n}\n", e.returnVals(p, fn.zero))
	}

	type fieldEntry struct{ name, expr string }
	entries := make([]fieldEntry, 0, len(p.fields))
	for _, f := range p.fields {
		val := "src." + f.read.name
		if f.read.getter {
			val += "()"
		}
		entries = append(entries, fieldEntry{f.dstName, e.fieldExpr(fn, f, val)})
	}

	lit := p.dst
	amp := ""
	if ptr, ok := types.Unalias(p.dst).(*types.Pointer); ok {
		lit = ptr.Elem()
		amp = "&"
	}
	fmt.Fprintf(buf, "return %s%s{\n", amp, e.typeExpr(lit))
	for _, entry := range entries {
		fmt.Fprintf(buf, "%s: %s,\n", entry.name, entry.expr)
	}
	buf.WriteString("}")
	if p.returnsError {
		buf.WriteString(", nil")
	}
	buf.WriteString("\n}\n")
}

// fieldExpr emits any statements needed to convert one field and returns
// the expression to place in the composite literal.
func (e *emitter) fieldExpr(fn *fnCtx, f fieldPlan, val string) string {
	if expr, ok := e.opExpr(f.conv, val); ok {
		return expr
	}
	// A fallible call at field level assigns straight into a fresh
	// temporary instead of going through a pre-declared variable.
	if call, errName, ok := e.fallibleCall(f.conv, val); ok {
		tv := e.tmp("v")
		fmt.Fprintf(fn.buf, "%s, %s := %s\n", tv, errName, call)
		e.emitErrCheck(fn, errName, f.dstName)
		return tv
	}
	// Taking the address of a pure expression gets a lighter form.
	if a, ok := f.conv.(opAddr); ok {
		if inner, ok := e.opExpr(a.elem, val); ok {
			tv := e.tmp("v")
			fmt.Fprintf(fn.buf, "%s := %s\n", tv, inner)
			return "&" + tv
		}
	}
	tv := e.tmp("v")
	fmt.Fprintf(fn.buf, "var %s %s\n", tv, e.typeExpr(f.dstType))
	e.emitAssign(fn, tv, val, f.conv, f.dstType, f.dstName)
	return tv
}

// opExpr renders o as a single expression; ok is false when statements
// are required.
func (e *emitter) opExpr(o op, val string) (string, bool) {
	switch v := o.(type) {
	case opDirect:
		return val, true
	case opTypeConv:
		return e.typeExpr(v.dst) + "(" + val + ")", true
	case opConvert:
		if v.conv.hasErr {
			return "", false
		}
		return e.funcRef(v.conv.fn) + "(" + val + ")", true
	case opMapper:
		if v.plan.returnsError {
			return "", false
		}
		return v.plan.name + "(" + val + ")", true
	default:
		return "", false
	}
}

// fallibleCall renders o as a call returning (value, error), reserving
// the error temporary.
func (e *emitter) fallibleCall(o op, val string) (call, errName string, ok bool) {
	switch v := o.(type) {
	case opConvert:
		if !v.conv.hasErr {
			return "", "", false
		}
		return e.funcRef(v.conv.fn) + "(" + val + ")", e.tmp("err"), true
	case opMapper:
		if !v.plan.returnsError {
			return "", "", false
		}
		return v.plan.name + "(" + val + ")", e.tmp("err"), true
	default:
		return "", "", false
	}
}

// emitAssign writes statements assigning the conversion of val to
// target, which must already be assignable.
func (e *emitter) emitAssign(fn *fnCtx, target, val string, o op, dstType types.Type, fieldName string) {
	if expr, ok := e.opExpr(o, val); ok {
		fmt.Fprintf(fn.buf, "%s = %s\n", target, expr)
		return
	}
	if call, errName, ok := e.fallibleCall(o, val); ok {
		tv := e.tmp("v")
		fmt.Fprintf(fn.buf, "%s, %s := %s\n", tv, errName, call)
		e.emitErrCheck(fn, errName, fieldName)
		fmt.Fprintf(fn.buf, "%s = %s\n", target, tv)
		return
	}
	switch v := o.(type) {
	case opDeref:
		tv := e.tmp("v")
		fmt.Fprintf(fn.buf, "if %s := %s; %s != nil {\n", tv, val, tv)
		e.emitAssign(fn, target, "*"+tv, v.elem, dstType, fieldName)
		fn.buf.WriteString("}\n")
	case opAddr:
		ptr, ok := types.Unalias(dstType).(*types.Pointer)
		if !ok {
			panic(fmt.Sprintf("kanna: opAddr destination %s is not a pointer", dstType))
		}
		elemT := ptr.Elem()
		tv := e.tmp("v")
		if expr, ok := e.opExpr(v.elem, val); ok {
			fmt.Fprintf(fn.buf, "%s := %s\n", tv, expr)
		} else {
			fmt.Fprintf(fn.buf, "var %s %s\n", tv, e.typeExpr(elemT))
			e.emitAssign(fn, tv, val, v.elem, elemT, fieldName)
		}
		fmt.Fprintf(fn.buf, "%s = &%s\n", target, tv)
	case opSlice:
		sl, ok := types.Unalias(v.dst).Underlying().(*types.Slice)
		if !ok {
			panic(fmt.Sprintf("kanna: opSlice destination %s is not a slice", v.dst))
		}
		elemT := sl.Elem()
		ts, ti, te := e.tmp("v"), e.tmp("i"), e.tmp("e")
		fmt.Fprintf(fn.buf, "if %s := %s; %s != nil {\n", ts, val, ts)
		fmt.Fprintf(fn.buf, "%s = make(%s, len(%s))\n", target, e.typeExpr(v.dst), ts)
		fmt.Fprintf(fn.buf, "for %s, %s := range %s {\n", ti, te, ts)
		e.emitAssign(fn, target+"["+ti+"]", te, v.elem, elemT, fieldName)
		fn.buf.WriteString("}\n}\n")
	default:
		panic(fmt.Sprintf("kanna: no statement form for %T", o))
	}
}

func (e *emitter) emitErrCheck(fn *fnCtx, errName, fieldName string) {
	fmtName := e.imports.Add("fmt", "fmt")
	fmt.Fprintf(fn.buf, "if %s != nil {\nreturn %s, %s.Errorf(\"map %s.%s: %%w\", %s)\n}\n",
		errName, fn.zero, fmtName, namedLabel(fn.plan.dst), fieldName, errName)
}

func (e *emitter) returnVals(p *funcPlan, zero string) string {
	if p.returnsError {
		return zero + ", nil"
	}
	return zero
}

func (e *emitter) funcRef(fn *types.Func) string {
	q := e.imports.Qualifier(fn.Pkg())
	if q == "" {
		return fn.Name()
	}
	return q + "." + fn.Name()
}
