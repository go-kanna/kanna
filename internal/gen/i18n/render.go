package i18n

import (
	"fmt"
	"go/format"
	"go/token"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/go-kanna/kanna/i18n"
	"github.com/go-kanna/kanna/internal/gen/i18n/locale"
)

const header = "// Code generated by kanna. DO NOT EDIT.\n\n"

// runtimePath is the import path of the runtime package. Its base name is
// importAlias, so the import needs no alias spec.
const runtimePath = "github.com/go-kanna/kanna/i18n"

// Render generates the Go source of the typed message package: one constructor
// per message, a Localizer accessor, and the catalogs of every locale compiled
// into a bundle. The output is deterministic and gofmt-formatted.
func Render(m Model, pkg string) ([]byte, error) {
	// token.IsIdentifier accepts the blank identifier, which is not a valid
	// package name.
	if pkg == "_" || !token.IsIdentifier(pkg) {
		return nil, fmt.Errorf("invalid package name %q", pkg)
	}
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n", pkg)

	// Each import is justified by what this run actually emits: the runtime by
	// any constructor or catalog, the language package only by the Localizer
	// accessor, which exists only when there are catalogs. format.Source does
	// not strip an unused import, so guessing generously here would emit a file
	// that does not compile.
	switch {
	case len(m.Catalogs) > 0:
		b.WriteString("\nimport (\n\t\"golang.org/x/text/language\"\n\n\t" +
			strconv.Quote(runtimePath) + "\n)\n")
	case len(m.Messages) > 0:
		b.WriteString("\nimport (\n\t" + strconv.Quote(runtimePath) + "\n)\n")
	}

	for _, msg := range m.Messages {
		b.WriteString("\n")
		writeMessage(&b, msg)
	}

	if len(m.Catalogs) > 0 {
		writeLocalizer(&b)
		writeBundle(&b, m)
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return src, nil
}

func writeMessage(b *strings.Builder, msg Message) {
	fmt.Fprintf(b, "// %s returns the %q message.\n", msg.FuncName, msg.Key)
	fmt.Fprintf(b, "func %s(", msg.FuncName)
	for i, p := range msg.Params {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%s %s", p.GoName, p.GoType)
	}
	fmt.Fprintf(b, ") %s.Message {\n", importAlias)
	if len(msg.Params) == 0 {
		fmt.Fprintf(b, "\treturn %s.Message{Key: %q}\n}\n", importAlias, msg.Key)
		return
	}
	fmt.Fprintf(b, "\treturn %s.Message{Key: %q, Args: []%s.Arg{\n", importAlias, msg.Key, importAlias)
	for _, p := range msg.Params {
		fmt.Fprintf(b, "\t\t{Name: %q, Value: %s},\n", p.Name, p.GoName)
	}
	b.WriteString("\t}}\n}\n")
}

func writeLocalizer(b *strings.Builder) {
	b.WriteString(`
// Localizer renders this package's messages in the compiled locale best
// matching tag. Messages missing from the matched locale fall back to the
// default language.
`)
	fmt.Fprintf(b, "func Localizer(tag language.Tag) %s.Localizer {\n", importAlias)
	b.WriteString("\treturn bundle.Localizer(tag)\n}\n")
}

// writeBundle emits the translations themselves: every locale the package was
// generated from, as one bundle built at init. This is what frees the runtime
// from reading locale files — by the time this variable exists, there is no
// file left to read.
func writeBundle(b *strings.Builder, m Model) {
	b.WriteString("\n// bundle holds every locale this package was generated from.\n")
	fmt.Fprintf(b, "var bundle = %s.NewBundle(%q,\n", importAlias, m.DefaultTag.String())
	for _, c := range m.Catalogs {
		writeCatalog(b, c)
	}
	b.WriteString(")\n")
}

func writeCatalog(b *strings.Builder, c locale.Catalog) {
	fmt.Fprintf(b, "\t%s.Catalog{Lang: %q, Entries: map[string]%s.Entry{\n",
		importAlias, c.Tag.String(), importAlias)
	for _, key := range sortedKeys(c.Entries) {
		entry := c.Entries[key]
		if entry.Plural == nil {
			fmt.Fprintf(b, "\t\t%q: {Single: %s},\n", key, templateExpr(entry.Single.Segments()))
			continue
		}
		fmt.Fprintf(b, "\t\t%q: {Plural: map[string]%s.Template{\n", key, importAlias)
		for _, category := range locale.PluralCategories {
			tmpl, ok := entry.Plural[category]
			if !ok {
				continue
			}
			fmt.Fprintf(b, "\t\t\t%q: %s,\n", category, segmentsExpr(tmpl.Segments()))
		}
		b.WriteString("\t\t}},\n")
	}
	b.WriteString("\t}},\n")
}

// templateExpr renders a template literal with its type, for positions where
// the type cannot be elided (an Entry field).
func templateExpr(segs []i18n.Segment) string {
	return importAlias + ".Template" + segmentsExpr(segs)
}

// segmentsExpr renders the braces-and-segments part of a template literal. In
// a map[string]Template value the element type is elided, so the plural
// variants use this form directly.
func segmentsExpr(segs []i18n.Segment) string {
	var b strings.Builder
	b.WriteString("{")
	for i, s := range segs {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(segmentExpr(s))
	}
	b.WriteString("}")
	return b.String()
}

func segmentExpr(s i18n.Segment) string {
	if s.Param == "" {
		return fmt.Sprintf("{Text: %q}", s.Text)
	}
	switch s.Kind {
	case i18n.KindString:
		return fmt.Sprintf("{Param: %q}", s.Param)
	case i18n.KindInt:
		return fmt.Sprintf("{Param: %q, Kind: %s.KindInt}", s.Param, importAlias)
	case i18n.KindNumber:
		return fmt.Sprintf("{Param: %q, Kind: %s.KindNumber}", s.Param, importAlias)
	default:
		panic(fmt.Sprintf("i18n: unknown Kind %d", s.Kind))
	}
}

func sortedKeys(entries map[string]locale.Entry) []string {
	return slices.Sorted(maps.Keys(entries))
}
