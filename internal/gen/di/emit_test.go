func TestEmit_SimpleChain(t *testing.T) {
	t.Parallel()

	src := `package myapp
type DB struct{}
type User struct{}
func NewDB() *DB { return nil }
func NewUser(db *DB) *User { return nil }
type Container struct {
	User *User ` + "`di:\"\"`" + `
}
`
	p := buildPlan(t, src)

	got, err := di.Emit("myapp", []di.Plan{p})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}

	want := `// Code generated by kanna. DO NOT EDIT.

package myapp

// NewContainer initializes dependencies and constructs Container.
func NewContainer() *Container {
	db := NewDB()
	user := NewUser(db)

	return &Container{
		User: user,
	}
}
`
	if string(got) != want {
		t.Errorf("output mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

