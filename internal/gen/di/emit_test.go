func TestEmit_NonNilableReturnUsesZeroValue(t *testing.T) {
	t.Parallel()

	// Return type = value struct (non-nilable). The provider chain must
	// include at least one (T, error) provider so writeSteps takes the
	// error branch and writes the zero-value return.
	src := `package myapp
type DB struct{}
type Bag struct{ DB *DB }
func NewDB() (*DB, error) { return nil, nil }
func NewBag(db *DB) Bag { return Bag{DB: db} }

//kanna:container returns=Bag
type app struct {
	B Bag ` + "`di:\"\"`" + `
}
`
	pkg := pkgtest.LoadFileAs(t, "myapp", src)
	pkgs := []*packages.Package{pkg}

	structs, dsS := scan.Structs(pkgs)
	if diag.HasErrors(dsS) {
		t.Fatalf("scan.Structs: %s", diag.Format(dsS))
	}
	cs, dsC := di.Containers(pkg.Fset, structs)
	if diag.HasErrors(dsC) {
		t.Fatalf("di.Containers: %s", diag.Format(dsC))
	}
	ps, dsP := di.Providers(pkgs)
	if diag.HasErrors(dsP) {
		t.Fatalf("di.Providers: %s", diag.Format(dsP))
	}

	var target di.Container
	for _, c := range cs {
		if c.StructName == "app" {
			target = c
			break
		}
	}
	pl, dsB := di.Build(target, di.NewIndex(ps), di.Options{})
	if diag.HasErrors(dsB) {
		t.Fatalf("di.Build: %s", diag.Format(dsB))
	}

	out, err := di.Emit("myapp", []di.Plan{pl})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	if !strings.Contains(string(out), "*new(Bag)") {
		t.Errorf("expected *new(Bag) zero-value return in error path, got:\n%s", out)
	}
}

