// buildPlan runs the whole pipeline on src and returns the plan for the
// "Container" struct. Tests in this file all use that conventional name, the
// package name "myapp" (which shows up in the generated output they assert on),
// and default plan options.
func buildPlan(t *testing.T, src string) di.Plan {
	t.Helper()

	const containerName = "Container"

	pkg := pkgtest.LoadFileAs(t, "myapp", src)
	pkgs := []*packages.Package{pkg}

	structs, dsS := scan.Structs(pkgs)
	if diag.HasErrors(dsS) {
		t.Fatalf("scan.Structs: %s", diag.Format(dsS))
	}
	cs, dsC := di.Containers(pkg.Fset, structs)
	if diag.HasErrors(dsC) {
		t.Fatalf("di.Containers: %s", diag.Format(dsC))
	}
	ps, dsP := di.Providers(pkgs)
	if diag.HasErrors(dsP) {
		t.Fatalf("di.Providers: %s", diag.Format(dsP))
	}

	var target di.Container
	for _, c := range cs {
		if c.StructName == containerName {
			target = c
			break
		}
	}
	if target.StructName == "" {
		t.Fatalf("container %q not found", containerName)
	}

	pl, dsB := di.Build(target, di.NewIndex(ps), di.Options{})
	if diag.HasErrors(dsB) {
		t.Fatalf("di.Build: %s", diag.Format(dsB))
	}
	return pl
}
