// load loads the packages to generate for, setting aside output of an earlier
// run that no longer type-checks.
//
// A container that changes can leave its di_gen.go referring to what is gone,
// and a package that does not type-check cannot be regenerated. The constructors
// in that file are planned again within the run, so nothing is lost by
// neutralizing it, in two steps: first only the function bodies, which is where
// stale output almost always breaks and which keeps hand-written callers
// compiling; then, if that is not enough, the whole file. Errors anywhere else
// never trigger this, so a real mistake is reported as it is.
//
// The second return value lists the files whose declarations were dropped
// entirely, for the caller to mention when errors remain.
func load(patterns []string, cfg packages.Config) (*packages.Result, []string, error) {
	res, err := packages.Load(patterns, cfg)
	if err != nil {
		return nil, nil, err //nolint:wrapcheck // the loader already prefixes its errors
	}

	stale := staleOutputs(res.Packages)
	if len(stale) == 0 {
		return res, nil, nil
	}

	cfg.Overlay = make(map[string][]byte, len(stale))
	for _, f := range stale {
		src, err := os.ReadFile(f.path)
		if err != nil {
			return nil, nil, fmt.Errorf("read %s: %w", f.path, err)
		}
		stubbed, err := stubBodies(f.path, src)
		if err != nil {
			return nil, nil, err
		}
		cfg.Overlay[f.path] = stubbed
	}
	res, err = packages.Load(patterns, cfg)
	if err != nil {
		return nil, nil, err //nolint:wrapcheck // the loader already prefixes its errors
	}

	still := staleOutputs(res.Packages)
	if len(still) == 0 {
		return res, nil, nil
	}
	dropped := make([]string, 0, len(still))
	for _, f := range still {
		cfg.Overlay[f.path] = fmt.Appendf(nil, "// Code generated by kanna. DO NOT EDIT.\n\npackage %s\n", f.pkgName)
		dropped = append(dropped, f.path)
	}
	res, err = packages.Load(patterns, cfg)
	if err != nil {
		return nil, nil, err //nolint:wrapcheck // the loader already prefixes its errors
	}
	return res, dropped, nil
}

// staleFile is a generated di_gen.go that a type error points into.
type staleFile struct {
	path    string
	pkgName string
}

// staleOutputs lists the generated di_gen.go files that type errors point into.
func staleOutputs(pkgs []*packages.Package) []staleFile {
	var out []staleFile
	for _, pkg := range scan.DedupePackages(pkgs) {
		if len(pkg.Errors) == 0 {
			continue
		}
		for path := range scan.GeneratedFiles(pkg) {
			if filepath.Base(path) != defaultOutputFile {
				continue
			}
			for _, e := range pkg.Errors {
				if strings.HasPrefix(e.Pos, path+":") {
					out = append(out, staleFile{path: path, pkgName: pkg.Name})
					break
				}
			}
		}
	}
	slices.SortFunc(out, func(a, b staleFile) int { return strings.Compare(a.path, b.path) })
	return out
}

// stubBodies keeps every declaration of a generated file but replaces each
// function body with a panic. Imports that only the bodies used are blanked, or
// the stub would fail on them instead.
func stubBodies(path string, src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}

	var bodies []*ast.BlockStmt
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		bodies = append(bodies, fn.Body)
		fn.Body = &ast.BlockStmt{List: []ast.Stmt{
			&ast.ExprStmt{X: &ast.CallExpr{
				Fun:  ast.NewIdent("panic"),
				Args: []ast.Expr{&ast.BasicLit{Kind: token.STRING, Value: strconv.Quote("stale")}},
			}},
		}}
	}

	// A comment inside a dropped body would otherwise be printed somewhere else.
	kept := file.Comments[:0]
	for _, cg := range file.Comments {
		inBody := slices.ContainsFunc(bodies, func(b *ast.BlockStmt) bool {
			return b.Pos() <= cg.Pos() && cg.End() <= b.End()
		})
		if !inBody {
			kept = append(kept, cg)
		}
	}
	file.Comments = kept

	for _, spec := range file.Imports {
		importPath, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}
		if !astutil.UsesImport(file, importPath) {
			spec.Name = ast.NewIdent("_")
		}
	}

	var buf bytes.Buffer
	if err := printer.Fprint(&buf, fset, file); err != nil {
		return nil, fmt.Errorf("print %s: %w", path, err)
	}
	return buf.Bytes(), nil
}
