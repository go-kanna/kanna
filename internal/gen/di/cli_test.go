func TestCLI_GeneratesIntoThePackageDirectory(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.25\n",
		"app.go": `package app

type DB struct{}
type User struct{}

func NewDB() *DB           { return nil }
func NewUser(db *DB) *User { return nil }

type Container struct {
	User *User ` + "`di:\"\"`" + `
}
`,
	})

	var out, errOut bytes.Buffer
	c := di.CLI{Out: &out, Err: &errOut, Dir: dir}

	code := c.Run([]string{"./..."})
	if code != exit.OK {
		t.Fatalf("exit code = %d, want %d\nstderr: %s", code, exit.OK, errOut.String())
	}

	generated := readFile(t, filepath.Join(dir, "di_gen.go"))
	for _, want := range []string{
		"// Code generated by kanna. DO NOT EDIT.",
		"package app",
		"func NewContainer() *Container {",
		"db := NewDB()",
		"user := NewUser(db)",
	} {
		if !strings.Contains(generated, want) {
			t.Errorf("generated file missing %q:\n%s", want, generated)
		}
	}

	// The path of the written file is reported on stdout.
	if !strings.Contains(out.String(), "di_gen.go") {
		t.Errorf("stdout = %q, want it to name the generated file", out.String())
	}
}

