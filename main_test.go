// The second task fails: what the report says is what is in the tree.
func TestGen_StopsAtTheFirstFailure(t *testing.T) {
	t.Parallel()

	dir := project(t, chain("-fail"))

	got := kanna(t, dir, "gen")

	if got.code != 1 {
		t.Fatalf("%+v", got)
	}
	want := "completed    c/c.go:3  kanna-fake  wrote c/c_gen.go\n" +
		"failed       b/b.go:5  kanna-fake  wrote b/half_gen.go\n" +
		"  ./a.go:1:1: error: it cannot be done\n" +
		"not run      a/a.go:5  kanna-fake\n" +
		"\n1 completed, 1 failed, 1 not run\n" +
		"2 files changed; completed changes remain in the working tree\n"
	if got.stdout != want {
		t.Errorf("stdout:\n%s\nwant:\n%s", got.stdout, want)
	}
	if !exists(filepath.Join(dir, "c", "c_gen.go")) || !exists(filepath.Join(dir, "b", "half_gen.go")) {
		t.Error("what completed is not in the tree")
	}
	if exists(filepath.Join(dir, "a", "a_gen.go")) {
		t.Error("the task after the failure ran")
	}
}

// Code calling what two tasks write: the first is told what the last writes.
func TestGen_TellsARunWhatIsComing(t *testing.T) {
	t.Parallel()

	dir := project(t, map[string]string{
		"m/m.go": "package m\n\n" +
			"//go:generate go tool kanna-fake -declares example.com/m/m.F -out f_gen.go " +
			"\"-body=func F() int { return 0 }\"\n" +
			"//go:generate go tool kanna-fake -declares example.com/m/m.G -out g_gen.go " +
			"\"-body=func G() int { return 0 }\"\n\n" +
			"var _, _ = F(), G()\n",
	})

	got := kanna(t, dir, "gen", "--plan")

	if got.code != 0 {
		t.Fatalf("%+v", got)
	}
	contains(t, got.stdout, "before: 2, which is told what it needs is coming — code in m calls")

	got = kanna(t, dir, "gen")

	if got.code != 0 {
		t.Fatalf("%+v", got)
	}
	contains(t, got.stdout, "wrote m/f_gen.go\n  pending: example.com/m/m.G\n",
		"wrote m/g_gen.go\n2 tasks, 2 files changed\n")
}

func TestGen_Plan(t *testing.T) {
	t.Parallel()

	dir := project(t, chain(""))
	before := tree(t, dir)

	got := kanna(t, dir, "gen", "--plan")

	if got.code != 0 {
		t.Fatalf("%+v", got)
	}
	contains(t, got.stdout, "1. c/c.go:3\n", "2. b/b.go:5\n", "3. a/a.go:5\n",
		"   run:    go tool kanna-fake -out a_gen.go\n", "   writes: a/a_gen.go\n",
		"   after:  2 — reads b, which kanna-fake writes into\n")
	sameTree(t, tree(t, dir), before)
}

func TestGen_Check(t *testing.T) {
	t.Parallel()

	dir := project(t, chain(""))
	kanna(t, dir, "gen")
	before := tree(t, dir)

	got := kanna(t, dir, "gen", "--check")

	if got != (outcome{stdout: "3 tasks up to date\n"}) {
		t.Errorf("%+v", got)
	}
	sameTree(t, tree(t, dir), before)
}

// What comes after a task that differs reads what is not on disk, so it is not
// told to be up to date, and what is not behind it is checked all the same.
func TestGen_CheckFindsADifference(t *testing.T) {
	t.Parallel()

	files := chain("")
	files["z/z.go"] = "package z\n\n//go:generate go tool kanna-fake -out z_gen.go\n"
	dir := project(t, files)
	kanna(t, dir, "gen")
	drifted := filepath.Join(dir, "b", "b_gen.go")
	stale := "// Code generated by kanna-fake. DO NOT EDIT.\n\npackage b\n"
	if err := os.WriteFile(drifted, []byte(stale), 0o600); err != nil {
		t.Fatal(err)
	}
	before := tree(t, dir)

	got := kanna(t, dir, "gen", "--check")

	if got.code != 1 {
		t.Fatalf("%+v", got)
	}
	contains(t, flat(got.stdout),
		"up to date c/c.go:3 kanna-fake\n",
		"failed b/b.go:5 kanna-fake\n ./b_gen.go: error: out of date; run go generate\n",
		"not checked a/a.go:5 kanna-fake\n",
		"up to date z/z.go:3 kanna-fake\n",
		"2 up to date, 1 failed, 1 not checked\n")
	sameTree(t, tree(t, dir), before)
}

