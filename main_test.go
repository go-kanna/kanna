// A generator from before -deps refuses the flag, which is the one thing that
// tells, whatever go.mod, a replace, or a workspace resolve it to.
func TestGen_AGeneratorTooOld(t *testing.T) {
	t.Parallel()

	old := "package main\n\nimport (\n\t\"flag\"\n\t\"fmt\"\n)\n\nfunc main() {\n" +
		"\tversion := flag.Bool(\"version\", false, \"\")\n\tflag.Parse()\n" +
		"\tif *version {\n\t\tfmt.Println(\"kanna-old v0.0.1\")\n\t}\n}\n"
	dir := project(t, map[string]string{
		"a/a.go":                "package a\n\n//go:generate go tool kanna-old\n",
		"cmd/kanna-old/main.go": old,
	})
	gomod := "module example.com/m\n\ngo 1.26.0\n\ntool example.com/m/cmd/kanna-old\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(gomod), 0o600); err != nil {
		t.Fatal(err)
	}

	got := kanna(t, dir, "gen")

	if got.code != 1 {
		t.Fatalf("%+v", got)
	}
	contains(t, got.stderr, "kanna-old v0.0.1 is too old", "go get -tool github.com/go-kanna/old/cmd/kanna-old@latest")
}

